    if [[ -r "$STATE_FILE" ]]; then
      old_port="$(cat "$STATE_FILE")"
      if [[ "$old_port" != "$PAQET_PORT" ]]; then
        remove_for_port "$old_port"
      fi
    fi
    add_rule raw PREROUTING -p tcp --dport "$PAQET_PORT" -j NOTRACK
    add_rule raw OUTPUT -p tcp --sport "$PAQET_PORT" -j NOTRACK
    add_rule mangle OUTPUT -p tcp --sport "$PAQET_PORT" --tcp-flags RST RST -j DROP
    printf '%s\n' "$PAQET_PORT" > "$STATE_FILE"
    ;;
  stop)
    port="$PAQET_PORT"
    [[ -r "$STATE_FILE" ]] && port="$(cat "$STATE_FILE")"
    remove_for_port "$port"
    rm -f "$STATE_FILE"
    ;;
  *)
    echo "Usage: $0 {start|stop}" >&2
    exit 2
    ;;
esac
